/**
 * ABOUTME: Behaviour tests for the garden harness, run against throwaway git repositories
 * with controlled commit dates and real transcript files. No mocks: every number comes from
 * the same git plumbing the CLI uses.
 */
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { after, describe, test } from 'node:test';

import { looksGenerated, resolveConfig } from './config.mjs';
import { DAY, parseBlamePorcelain, rewrittenRanges } from './git.mjs';
import { weekLabel, weekStart } from './history.mjs';
import {
  commitType,
  compareWindows,
  countSignal,
  hotspots,
  shareSignal,
  verdict,
  windowOutcomes,
} from './outcomes.mjs';
import { formatWindow } from './report.mjs';
import { prOutcomes, pushOutcomes } from './sources.mjs';
import { signature, snapshot, sqlFunctions } from './state.mjs';

const T0 = Date.UTC(2026, 0, 5) / 1000;
const roots = [];
after(() => roots.forEach((r) => rmSync(r, { recursive: true, force: true })));

function repo() {
  const root = mkdtempSync(join(tmpdir(), 'garden-test-'));
  roots.push(root);
  const run = (args, env = {}) =>
    execFileSync('git', args, {
      cwd: root,
      env: { ...process.env, ...env },
      encoding: 'utf8',
    });
  run(['init', '-q', '-b', 'main']);
  run(['config', 'user.email', 'garden@example.com']);
  run(['config', 'user.name', 'Garden']);
  run(['config', 'commit.gpgsign', 'false']);
  return {
    root,
    write(path, text) {
      mkdirSync(dirname(join(root, path)), { recursive: true });
      writeFileSync(join(root, path), text);
    },
    remove(path) {
      run(['rm', '-q', path]);
    },
    commit(subject, at) {
      const date = `@${at} +0000`;
      run(['add', '-A']);
      run(['commit', '-q', '--allow-empty', '-m', subject], {
        GIT_AUTHOR_DATE: date,
        GIT_COMMITTER_DATE: date,
      });
      return run(['rev-parse', 'HEAD']).trim();
    },
  };
}

const lines = (n, prefix = 'line') =>
  Array.from({ length: n }, (_, i) => `const ${prefix}${i} = ${i};`).join(
    '\n',
  ) + '\n';
const config = (extra = {}) =>
  resolveConfig({ branch: 'main', reworkSample: 1000, ...extra });

describe('snapshot', () => {
  test('counts size, escapes, suppressions and test weight, skipping ignored and generated files', () => {
    const r = repo();
    r.write(
      'src/big.ts',
      `${lines(900)}const x = y as any;\n// oxlint-disable-next-line\n`,
    );
    r.write('src/small.ts', 'export const a = b as unknown as C;\n');
    r.write(
      'src/thing.spec.ts',
      "vi.mock('./x');\nit('a', () => { expect(f).toHaveBeenCalledWith(1); });\ntest.each([1])('b', () => {});\n",
    );
    r.write(
      'src/out.ts',
      `/** @generated by codegen */\n${lines(2000)}const z = q as any;\n`,
    );
    r.write('node_modules/pkg/index.js', lines(5000));
    r.write('README.md', '# readme\n');
    const sha = r.commit('feat: start', T0);
    const s = snapshot(r.root, sha, config());

    assert.deepEqual(s.files, { source: 2, test: 1, generatedSkipped: 1 });
    assert.equal(s.lines.source, 903);
    assert.equal(s.largeFiles.count, 1);
    assert.deepEqual(s.largeFiles.top, [{ path: 'src/big.ts', lines: 902 }]);
    assert.equal(s.typeEscapes.source['as any'], 1);
    assert.equal(s.typeEscapes.source['as unknown as'], 1);
    assert.equal(s.typeEscapes.totalSource, 2);
    assert.equal(s.suppressions.total, 1);
    assert.deepEqual(s.tests, {
      cases: 2,
      mockModules: 1,
      callAssertions: 1,
      assertions: 1,
    });
    assert.equal(s.sql, null);
  });

  test('measures each SQL function at its latest migration definition, honouring drops', () => {
    const r = repo();
    const fn = (name, body) =>
      `create or replace function public.${name}() returns void language plpgsql as $$\n${body}\n$$;\n`;
    r.write(
      'db/migrations/001.sql',
      fn('big_one', 'v1') + fn('gone', 'begin\n'.repeat(20)),
    );
    r.write(
      'db/migrations/002.sql',
      fn('big_one', 'begin\n'.repeat(10)) + fn('small_one', 'v1'),
    );
    r.write(
      'db/migrations/003.sql',
      'drop function if exists public.gone();\n',
    );
    r.write('db/schemas/10-fns.sql', fn('big_one', 'begin\n'.repeat(10)));
    const sha = r.commit('feat: db', T0);
    const s = snapshot(
      r.root,
      sha,
      config({
        sql: {
          schemas: ['db/schemas/*.sql'],
          migrations: ['db/migrations/*.sql'],
          largeFunctionLines: 5,
        },
      }),
    );

    assert.equal(s.sql.migrations, 3);
    assert.equal(s.sql.functions, 2);
    assert.equal(s.sql.largeFunctions.count, 1);
    assert.equal(s.sql.largestFunctions[0].name, 'big_one');
    assert.equal(s.sql.largestFunctions[0].path, 'db/migrations/002.sql');
    assert.deepEqual(s.sql.mostRedefined[0], { name: 'big_one', count: 2 });
  });

  test('dropping one overload keeps the others, matched on argument types alone', () => {
    const r = repo();
    const fn = (name, args, body) =>
      `create or replace function public.${name}(${args}) returns void language plpgsql as $$\n${body}\n$$;\n`;
    r.write(
      'db/migrations/001.sql',
      fn(
        'next_run',
        'p_cron varchar(64), p_tz varchar, p_from timestamptz default now()',
        'a',
      ) + fn('next_run', 'p_cron text, p_tz text', 'b'),
    );
    r.write(
      'db/migrations/002.sql',
      'DROP FUNCTION public.next_run(VARCHAR, character varying, TIMESTAMP WITH TIME ZONE);\n',
    );
    const s = snapshot(
      r.root,
      r.commit('feat: db', T0),
      config({ sql: { migrations: ['db/migrations/*.sql'] } }),
    );
    assert.equal(s.sql.functions, 1);
    assert.deepEqual(s.sql.mostRedefined, [{ name: 'next_run', count: 2 }]);
  });

  test('signature keeps input types only', () => {
    assert.equal(
      signature(
        'p_id uuid, OUT total bigint, IN p_days int = 7, VARIADIC tags text[]',
      ),
      'uuid,integer,text[]',
    );
    assert.equal(
      signature('double precision, "p_at" timestamp without time zone'),
      'double precision,timestamp',
    );
    assert.equal(signature(''), '');
  });

  test('a body without a dollar quote does not swallow the next function', () => {
    const sql =
      'create function public.atomic_one(a int) returns int language sql begin atomic select a; end;\n' +
      'create function public.dollar_one() returns void language plpgsql as $$\nbegin\nnull;\nend\n$$;\n';
    assert.deepEqual(sqlFunctions(sql), [
      { name: 'atomic_one', signature: 'integer', lines: 0 },
      { name: 'dollar_one', signature: '', lines: 5 },
    ]);
  });

  test('sqlFunctions reads quoted, schema-qualified names and custom dollar tags', () => {
    const found = sqlFunctions(
      'CREATE FUNCTION "private"."Thing"(a int) RETURNS int AS $body$\nselect 1;\nselect 2;\n$body$ LANGUAGE sql;',
    );
    assert.deepEqual(found, [
      { name: 'private.thing', signature: 'integer', lines: 4 },
    ]);
    assert.deepEqual(
      sqlFunctions('DROP FUNCTION IF EXISTS public.old_thing(int);'),
      [{ name: 'old_thing', signature: 'integer', dropped: true }],
    );
    assert.deepEqual(sqlFunctions('drop function old_thing;'), [
      { name: 'old_thing', signature: null, dropped: true },
    ]);
  });
});

describe('outcomes', () => {
  test('commitType reads conventional prefixes and falls back to other', () => {
    assert.equal(commitType('fix(db): stop it'), 'fix');
    assert.equal(commitType('feat!: break it'), 'feat');
    assert.equal(commitType('Merge branch main'), 'other');
    assert.equal(commitType('wip: thing'), 'other');
    assert.equal(
      commitType('[codex] Fix changelog description XSS (#1260)'),
      'fix',
    );
    assert.equal(commitType('Simplify blog index copy'), 'refactor');
    assert.equal(commitType('Add trial team health to admin'), 'feat');
    assert.equal(commitType('Reduce Sentry noise'), 'other');
  });

  test('rework counts rewritten lines younger than the limit, and never whole-file deletes', async () => {
    const r = repo();
    r.write('src/a.ts', lines(10));
    r.write('src/gone.ts', lines(50));
    r.commit('feat: a', T0);
    r.write(
      'src/a.ts',
      lines(10)
        .replace('const line0 = 0;', 'const line0 = 100;')
        .replace('const line1 = 1;', 'const line1 = 101;'),
    );
    r.commit('fix: old lines', T0 + 30 * DAY);
    r.write(
      'src/a.ts',
      lines(10)
        .replace('const line1 = 1;', 'const line1 = 201;')
        .replace('const line0 = 0;', 'const line0 = 200;'),
    );
    r.remove('src/gone.ts');
    r.commit('fix: new lines', T0 + 31 * DAY);

    const o = await windowOutcomes(
      r.root,
      config(),
      T0 + 29 * DAY,
      T0 + 32 * DAY,
    );
    assert.equal(o.commits, 2);
    assert.deepEqual(o.byType, { fix: 2 });
    assert.equal(o.fixShare, 1);
    assert.deepEqual(o.rework, { lines: 4, recent: 2, share: 0.5 });
    assert.equal(o.netDeletingShare, 0.5);
  });

  test('hotspots rank repeatedly fixed files by fixes and size', () => {
    const r = repo();
    r.write('src/big.ts', lines(400));
    r.write('src/small.ts', lines(4));
    r.commit('feat: start', T0);
    for (let i = 1; i <= 3; i += 1) {
      r.write('src/big.ts', lines(400, `b${i}`));
      r.write('src/small.ts', lines(4, `s${i}`));
      r.commit(`fix: round ${i}`, T0 + i * DAY);
    }
    const spots = hotspots(r.root, config(), T0, T0 + 10 * DAY);
    assert.deepEqual(
      spots.map((s) => [s.path, s.fixes, s.commits]),
      [
        ['src/big.ts', 3, 4],
        ['src/small.ts', 3, 4],
      ],
    );
    assert.ok(spots[0].score > spots[1].score);
  });

  test('signals need enough evidence before they call a direction', () => {
    assert.equal(countSignal(1, 2), 'unmeasured');
    assert.equal(countSignal(10, 4), 'better');
    assert.equal(countSignal(4, 10), 'worse');
    assert.equal(countSignal(10, 9), 'flat');
    assert.equal(
      shareSignal({ lines: 50, share: 0.5 }, { lines: 500, share: 0.1 }),
      'unmeasured',
    );
    assert.equal(
      shareSignal({ lines: 500, share: 0.4 }, { lines: 500, share: 0.2 }),
      'better',
    );
    assert.equal(verdict(['better', 'worse'], true), 'mixed');
    assert.equal(verdict(['better', 'unmeasured'], true), 'improved');
    assert.equal(verdict(['flat', 'flat'], true), 'no clear change');
    assert.equal(verdict(['unmeasured', 'unmeasured'], true), 'unmeasured');
    assert.equal(verdict(['better'], false), 'still measuring');
  });

  test('compareWindows reads fixes on the touched files either side of the intervention', async () => {
    const r = repo();
    r.write('src/a.ts', lines(20));
    r.write('src/other.ts', lines(20));
    r.commit('feat: a', T0);
    for (let i = 1; i <= 5; i += 1) {
      r.write('src/a.ts', lines(20, `v${i}`));
      r.commit(`fix: a ${i}`, T0 + i * DAY);
    }
    r.write('src/a.ts', lines(5, 'clean'));
    const sha = r.commit('refactor: simplify a', T0 + 10 * DAY);
    r.write('src/other.ts', lines(20, 'o'));
    r.commit('fix: other', T0 + 12 * DAY);
    r.write('src/other.ts', lines(20, 'p'));
    r.commit('feat: later', T0 + 30 * DAY);

    const commit = { sha, time: T0 + 10 * DAY };
    const attributable = config({ sharedFileShare: 1.1 });
    const result = await compareWindows(
      r.root,
      attributable,
      commit,
      new Set(['src/a.ts']),
      14,
      T0 + 40 * DAY,
    );
    assert.equal(result.before.fixes, 5);
    assert.equal(result.after.fixes, 0);
    assert.equal(result.signals.fixes, 'better');
    assert.equal(result.result, 'improved');

    const early = await compareWindows(
      r.root,
      attributable,
      commit,
      new Set(['src/a.ts']),
      14,
      T0 + 15 * DAY,
    );
    assert.equal(early.result, 'still measuring');

    // Every commit before it touched src/a.ts, so by default the file is too shared to attribute.
    const shared = await compareWindows(
      r.root,
      config(),
      commit,
      new Set(['src/a.ts']),
      14,
      T0 + 40 * DAY,
    );
    assert.deepEqual(shared.shared, ['src/a.ts']);
    assert.equal(shared.measured, 0);
    assert.equal(shared.result, 'unmeasured');

    // The branch's last commit is at day 30; a 40-day after window it never reached is unmeasured.
    const stale = await compareWindows(
      r.root,
      attributable,
      commit,
      new Set(['src/a.ts']),
      40,
      T0 + 90 * DAY,
    );
    assert.equal(stale.branchBehind, true);
    assert.equal(stale.result, 'unmeasured');

    // Fetched after that window closed (the remote-tracking ref was written on day 80), the same
    // quiet branch is measured.
    execFileSync(
      'git',
      ['update-ref', '-m', 'fetch', 'refs/remotes/origin/main', 'HEAD'],
      {
        cwd: r.root,
        env: { ...process.env, GIT_COMMITTER_DATE: `@${T0 + 80 * DAY} +0000` },
      },
    );
    const fetched = await compareWindows(
      r.root,
      config({ sharedFileShare: 1.1, branch: 'origin/main' }),
      commit,
      new Set(['src/a.ts']),
      40,
      T0 + 90 * DAY,
    );
    assert.equal(fetched.branchBehind, false);
  });
});

describe('diff ranges', () => {
  test('a removed SQL comment line does not hide the hunks after it, whatever the diff config', async () => {
    const r = repo();
    const sql = (a, b) =>
      `-- header\nselect ${a};\n-- note\nselect 1;\nselect 2;\nselect ${b};\n`;
    r.write('db/f.sql', sql('a', 'b'));
    const parent = r.commit('feat: sql', T0);
    r.write(
      'db/f.sql',
      sql('a', 'b').replace('-- note\n', '').replace('select b;', 'select c;'),
    );
    const sha = r.commit('fix: sql', T0 + DAY);
    execFileSync('git', ['config', 'diff.noprefix', 'true'], { cwd: r.root });
    execFileSync('git', ['config', 'color.diff', 'always'], { cwd: r.root });
    const ranges = await rewrittenRanges(r.root, parent, sha, ['db/f.sql']);
    assert.deepEqual(ranges.get('db/f.sql'), [
      [3, 1],
      [6, 1],
    ]);
  });
});

describe('parsing helpers', () => {
  test('blame porcelain splits boundary lines from recent ones', () => {
    const a = 'a'.repeat(40);
    const b = 'b'.repeat(40);
    const out = [
      `${a} 1 1 2`,
      'author X',
      'boundary',
      '\tline',
      `${a} 2 2`,
      '\tline',
      `${b} 3 3 1`,
      'author Y',
      '\tline',
      '',
    ].join('\n');
    assert.deepEqual(parseBlamePorcelain(out), { lines: 3, recent: 1 });
  });

  test('generated headers are recognised without catching ordinary mentions', () => {
    assert.ok(looksGenerated('/** Generated by `pnpm gen`; do not edit. */'));
    assert.ok(looksGenerated('// @generated'));
    assert.ok(!looksGenerated('// Builds the generated summary for the brief'));
  });

  test('ISO weeks start on Monday 00:00 UTC', () => {
    const monday = Date.UTC(2026, 10, 9) / 1000;
    assert.equal(weekStart(monday + 3 * DAY + 5), monday);
    assert.equal(weekLabel(monday), '2026-W46');
    assert.equal(weekLabel(Date.UTC(2026, 0, 1) / 1000 - 3 * DAY), '2026-W01');
  });
});

describe('review load', () => {
  test('a PR whose fetched commits all follow its first review is left out, not undercounted', () => {
    const pr = (total, dates) => ({
      commits: {
        totalCount: total,
        nodes: dates.map((d) => ({ commit: { committedDate: d } })),
      },
      reviews: { nodes: [{ submittedAt: '2026-01-02' }] },
      reviewThreads: { totalCount: 0 },
    });
    const out = prOutcomes([
      pr(3, ['2026-01-01', '2026-01-03', '2026-01-04']),
      pr(150, [
        '2026-01-03',
        '2026-01-04',
        '2026-01-05',
        '2026-01-06',
        '2026-01-07',
      ]),
      pr(120, ['2026-01-01', '2026-01-05']),
    ]);
    assert.deepEqual(out.commitsAfterReview, { median: 2, p90: 2 });
  });
});

describe('window report', () => {
  test('a window with no merged PRs reads Unmeasured, not null', () => {
    const o = {
      since: T0,
      until: T0 + DAY,
      commits: 0,
      byType: {},
      fixShare: null,
      cleanupShare: null,
      lines: { added: 0, deleted: 0, net: 0 },
      rework: { share: null },
      fixRework: { share: null },
      reworkSampled: { all: 0, fix: 0 },
    };
    const text = formatWindow(o, prOutcomes([]), null);
    assert.ok(!text.includes('null'), text);
    assert.match(text, /Commits per PR, median \/ p90\s+Unmeasured/);
  });
});

describe('push transcripts', () => {
  test('foreground pushes are timed once each, across resumed copies of a session', async () => {
    const root = mkdtempSync(join(tmpdir(), 'garden-tx-'));
    roots.push(root);
    const at = (s) => new Date((T0 + s) * 1000).toISOString();
    const use = (id, command, s, input = {}) =>
      JSON.stringify({
        timestamp: at(s),
        message: {
          content: [
            {
              type: 'tool_use',
              id,
              name: 'Bash',
              input: { command, ...input },
            },
          ],
        },
      });
    const result = (id, s, extra = {}) =>
      JSON.stringify({
        timestamp: at(s),
        message: {
          content: [{ type: 'tool_result', tool_use_id: id, ...extra }],
        },
      });
    const session = [
      use('p1', 'git push origin HEAD', 0),
      result('p1', 300),
      use('p2', 'cd x && git push -u origin b', 400),
      result('p2', 460, { is_error: true }),
      use('bg', 'git push', 500, { run_in_background: true }),
      result('bg', 501),
      use('ls', 'git status', 600),
      result('ls', 601),
    ].join('\n');
    mkdirSync(join(root, '-home-me-myrepo'));
    mkdirSync(join(root, '-home-me-otherrepo'));
    writeFileSync(join(root, '-home-me-myrepo', 'one.jsonl'), session);
    writeFileSync(join(root, '-home-me-myrepo', 'resumed.jsonl'), session);
    writeFileSync(
      join(root, '-home-me-otherrepo', 'x.jsonl'),
      session.replaceAll('p1', 'q1'),
    );

    const pushes = await pushOutcomes(
      { claudeProjectsDir: root, match: 'myrepo' },
      T0 - DAY,
      T0 + DAY,
    );
    assert.deepEqual(pushes, {
      pushes: 2,
      medianSeconds: 300,
      p90Seconds: 300,
      failureShare: 0.5,
    });
    assert.equal(
      await pushOutcomes(
        { claudeProjectsDir: root, match: 'nothing' },
        T0 - DAY,
        T0 + DAY,
      ),
      null,
    );
  });
});
